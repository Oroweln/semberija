			<p class="lead">Semberija.app follows the principles of the General Data Protection Regulation (GDPR) in its handling of personal data.</p>

			<h2>GDPR Principles</h2>
			<p>Our data processing practices are guided by the following GDPR principles:</p>
			<ul>
				<li><strong>Lawfulness, fairness, and transparency</strong> — Personal data is processed lawfully, fairly, and in a transparent manner.</li>
				<li><strong>Purpose limitation</strong> — Data is collected for specified, explicit, and legitimate purposes and not further processed in a manner incompatible with those purposes.</li>
				<li><strong>Data minimization</strong> — Personal data collected is adequate, relevant, and limited to what is necessary in relation to the purposes for which it is processed.</li>
				<li><strong>Accuracy</strong> — Personal data is accurate and, where necessary, kept up to date.</li>
				<li><strong>Storage limitation</strong> — Personal data is kept in a form which permits identification of data subjects for no longer than is necessary.</li>
				<li><strong>Integrity and confidentiality</strong> — Personal data is processed in a manner that ensures appropriate security, including protection against unauthorized or unlawful processing and against accidental loss, destruction, or damage.</li>
			</ul>

			<h2>Your Rights Under GDPR</h2>
			<p>Users located in the European Union have the following rights regarding their personal data:</p>
			<ul>
				<li><strong>Right of access</strong> — You have the right to request a copy of the personal data we hold about you.</li>
				<li><strong>Right to rectification</strong> — You have the right to request correction of inaccurate or incomplete personal data.</li>
				<li><strong>Right to erasure</strong> — You have the right to request the deletion of your personal data under certain circumstances.</li>
				<li><strong>Right to restriction of processing</strong> — You have the right to request that we restrict the processing of your personal data in certain situations.</li>
				<li><strong>Right to data portability</strong> — You have the right to receive your personal data in a structured, commonly used, and machine-readable format.</li>
				<li><strong>Right to object</strong> — You have the right to object to the processing of your personal data in certain circumstances.</li>
			</ul>

			<h2>Lawful Basis for Processing</h2>
			<p>We process personal data on the following lawful bases:</p>
			<ul>
				<li>Consent provided by the user</li>
				<li>Performance of a contract or steps taken prior to entering into a contract</li>
				<li>Compliance with a legal obligation</li>
				<li>Legitimate interests pursued by the platform</li>
			</ul>

			<h2>Data Transfers</h2>
			<p>Where personal data is transferred outside of the European Economic Area, we ensure that appropriate safeguards are in place to protect the data in accordance with GDPR requirements.</p>

			<h2>Submitting a GDPR Request</h2>
			<p>All GDPR related requests can be sent to:</p>
			<p><a href="mailto:info@semberija.app">info@semberija.app</a></p>
			<p>We will respond to all legitimate requests within 30 days. In some cases, particularly for complex requests, we may take up to two additional months.</p>

